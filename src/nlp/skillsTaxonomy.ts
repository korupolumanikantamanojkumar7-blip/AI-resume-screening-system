export const SKILL_BY_CANONICAL = new Map<string, SkillTaxonomyEntry>(
  SKILLS_TAXONOMY.map((s) => [s.canonical, s])
);

export const ALIAS_TO_CANONICAL = new Map<string, string>();
for (const entry of SKILLS_TAXONOMY) {
  ALIAS_TO_CANONICAL.set(entry.canonical.toLowerCase(), entry.canonical);
  ALIAS_TO_CANONICAL.set(entry.displayName.toLowerCase(), entry.canonical);
  for (const alias of entry.aliases) {
    ALIAS_TO_CANONICAL.set(alias.toLowerCase(), entry.canonical);
  }
}

export function normalizeSkillName(raw: string): string {
  const cleaned = raw.trim().toLowerCase();
  return ALIAS_TO_CANONICAL.get(cleaned) ?? cleaned;
}

export function getSkillDisplayName(canonical: string): string {
  const found = SKILL_BY_CANONICAL.get(canonical.toLowerCase());
  if (found) return found.displayName;
  return canonical
    .split(/\s+/)
    .map((w) => (w.length > 0 ? w[0].toUpperCase() + w.slice(1) : w))
    .join(' ');
}

export function getTaxonomyStats(): { totalSkills: number; totalAliases: number } {
  const totalAliases = SKILLS_TAXONOMY.reduce((sum, s) => sum + s.aliases.length, 0);
  return { totalSkills: SKILLS_TAXONOMY.length, totalAliases };
}
